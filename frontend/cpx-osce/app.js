function aiHintReply(c, kind) {
  const guide = studyGuideFor(c);
  const session = aiSessionFor(c.id);
  if (kind === "first") {
    return { label: "첫 문장", text: `“${guide.opening}”` };
  }
  if (kind === "plan") {
    return { label: "치료계획", text: treatmentPlanReply(c) };
  }
  if (kind === "missing") {
    const missing = window.CpxAI.liveMissing(aiCtx(c), session.messages, 3);
    return {
      label: "누락 확인",
      text: missing.length
        ? `지금까지 대화 기준으로 아직 안 물어본 필수 항목입니다. ${missing.map((line, index) => `${index + 1}) ${line}`).join(" ")}`
        : "지금까지 필수 항목은 잘 챙기고 있습니다. 이제 설명과 마무리 문장을 준비하세요."
    };
  }
  return {
    label: "마무리",
    text: `요약 → 계획 → 경고 증상 → 질문 확인 순서로 닫으세요. “${guide.closing}” 마지막에 ‘마무리했습니다’라고 입력하면 면담이 종료됩니다.`
  };
}

function sendAiHint(kind) {
  const c = activeCase();
  const session = aiSessionFor(c.id);
  if (session.status !== "live" || session.noHints) return;
  const hint = aiHintReply(c, kind);
  session.messages.push({ role: "hint", label: hint.label, text: hint.text });
  session.hintsUsed = [...(session.hintsUsed || []), kind];
  focusAiInput = true;
  saveState();
  render();
}

function toggleAiListening() {
  const voice = window.CpxVoice;
  if (!voice || !voice.sttSupported) return;
  if (aiListening) {
    voice.stop();
    return;
  }
  const c = activeCase();
  const started = voice.start({
    onInterim: (text) => {
      const input = document.getElementById("aiInput");
      if (input) input.value = text;
    },
    onFinal: (text) => {
      aiListening = false;
      if (state.activeCaseId === c.id) sendAiMessage(text);
    },
    onEnd: () => {
      if (aiListening) {
        aiListening = false;
        render();
      }
    },
    onError: (code) => {
      aiListening = false;
      const session = aiSessionFor(c.id);
      if (code === "not-allowed" || code === "service-not-allowed") {
        session.messages.push({ role: "system", text: "마이크 권한이 차단되어 있습니다. 주소창의 마이크 아이콘에서 허용해 주세요." });
      }
      saveState();
      render();
    }
  });
  if (started) {
    aiListening = true;
    render();
  }
}

