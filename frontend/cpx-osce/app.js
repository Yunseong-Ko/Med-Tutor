function checkKey(caseId, sectionId, index) {
  return `${caseId}::${sectionId}::${index}`;
}

function scoreCase(c) {
  let total = 0;
  let checked = 0;
  const bySection = [];
  const missedCritical = [];

  c.sections.forEach((section) => {
    let sectionTotal = 0;
    let sectionChecked = 0;
    section.items.forEach((entry, index) => {
      total += 1;
      sectionTotal += 1;
      const key = checkKey(c.id, section.id, index);
      if (state.checked[key]) {
        checked += 1;
        sectionChecked += 1;
      } else if (entry.critical) {
        missedCritical.push(entry.text);
      }
    });
    bySection.push({
      id: section.id,
      title: section.title.replace(" · ", "/"),
      score: sectionTotal ? Math.round((sectionChecked / sectionTotal) * 100) : 0,
      checked: sectionChecked,
      total: sectionTotal
    });
  });

  return {
    total,
    checked,
    percent: total ? Math.round((checked / total) * 100) : 0,
    bySection,
    missedCritical
  };
}

function filteredCases() {
  const query = state.query.trim().toLowerCase();
  return cases.filter((c) => {
    const categoryOk = state.filter === "전체" || c.category === state.filter;
    const haystack = `${c.category} ${c.presentation} ${c.diagnosis} ${c.focus}`.toLowerCase();
    return categoryOk && (!query || haystack.includes(query));
  });
}

function stats() {
  const scores = cases.map(scoreCase);
  const done = scores.filter((s) => s.percent >= 80).length;
  const avg = Math.round(scores.reduce((sum, s) => sum + s.percent, 0) / scores.length);
  const criticalTotal = scores.reduce((sum, s) => sum + s.bySection.reduce((inner, section) => inner + section.total, 0), 0);
  return { done, avg, criticalTotal };
}

