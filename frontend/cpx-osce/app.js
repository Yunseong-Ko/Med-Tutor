function updateTimerDom() {
  const time = document.getElementById("timerTime");
  const fill = document.getElementById("phaseFill");
  const name = document.getElementById("phaseName");
  const hint = document.getElementById("phaseHint");
  if (!time || !fill || !name || !hint) return;
  const remaining = Math.max(0, state.timer.remaining);
  const elapsed = STATION_SECONDS - remaining;
  const minutes = Math.floor(remaining / 60);
  const seconds = remaining % 60;
  time.textContent = `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
  fill.style.width = `${Math.min(100, Math.round((elapsed / STATION_SECONDS) * 100))}%`;
  const phase = currentPhase(elapsed);
  name.textContent = phase.name;
  hint.textContent = phase.hint;
}

function currentPhase(elapsed) {
  if (elapsed < 60) return { name: "개시", hint: "환자 확인, 주호소 개방형 질문, 위험 신호 스크리닝." };
  if (elapsed < 7 * 60) return { name: "문진", hint: "핵심 감별을 좁히는 문진을 우선 진행하세요." };
  if (elapsed < 9 * 60) return { name: "진찰", hint: "필요한 진찰과 검사를 말로 선언하고 동의를 챙기세요." };
  if (elapsed < 11 * 60) return { name: "설명", hint: "가능성 높은 원인, 검사, 치료 계획을 쉬운 말로 설명하세요." };
  if (elapsed < STATION_SECONDS) return { name: "마무리", hint: "요약, 질문 확인, 경고 증상, 재내원 계획을 닫습니다." };
  return { name: "종료", hint: "채점하고 필수 누락을 확인하세요." };
}

function startTimer() {
  stopTimer();
  state.timer.running = true;
  timerId = window.setInterval(() => {
    state.timer.remaining = Math.max(0, state.timer.remaining - 1);
    if (state.timer.remaining <= 0) {
      stopTimer();
      state.timer.remaining = 0;
    }
    updateTimerDom();
  }, 1000);
  render();
}

function stopTimer() {
  if (timerId) window.clearInterval(timerId);
  timerId = null;
  state.timer.running = false;
}

function resetTimer() {
  stopTimer();
  state.timer.remaining = STATION_SECONDS;
  saveState();
  render();
}

function setActiveCase(id) {
  if (!cases.some((c) => c.id === id)) return;
  if (state.activeCaseId === id) return;
  rememberSidebarScroll();
  stopTimer();
  if (window.CpxVoice) {
    window.CpxVoice.stopSpeaking();
    window.CpxVoice.stop();
  }
  aiListening = false;
  state.activeCaseId = id;
  state.timer.remaining = STATION_SECONDS;
  saveState();
  render();
}

function resetCase(caseId) {
  const prefix = `${caseId}::`;
  Object.keys(state.checked).forEach((key) => {
    if (key.startsWith(prefix)) delete state.checked[key];
  });
  delete state.notes[caseId];
  delete state.coachMessages[caseId];
  delete state.aiSessions[caseId];
  state.coachDraft = "";
  state.aiDraft = "";
  saveState();
  render();
}

