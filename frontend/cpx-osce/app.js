function startAiSession() {
  const c = activeCase();
  const session = aiSessionFor(c.id);
  const persona = window.CpxAI.personaFor(c);
  session.status = "live";
  session.result = null;
  session.noHints = Boolean(session.noHints);
  session.hintsUsed = [];
  session.persona = { name: persona.name, speaker: persona.speaker };
  session.messages = [
    { role: "system", text: "실전 시작. 문 앞 정보를 확인했다고 생각하고, 인사와 환자 확인부터 시작하세요. 12분 타이머가 함께 돌아갑니다." }
  ];
  state.activeTab = "ai";
  state.aiDraft = "";
  state.timer.remaining = STATION_SECONDS;
  focusAiInput = true;
  saveState();
  startTimer();
  window.CpxAI.probeEngine().then((engine) => {
    const current = aiSessionFor(c.id);
    if (current.engine !== engine) {
      current.engine = engine;
      saveState();
      if (state.activeCaseId === c.id && state.activeTab === "ai") render();
    }
  });
}

function sendAiMessage(rawText) {
  const text = String(rawText || "").trim();
  if (!text || aiBusy) return;
  const c = activeCase();
  const session = aiSessionFor(c.id);
  if (session.status !== "live") return;
  session.messages.push({ role: "student", text });
  state.aiDraft = "";
  const finishing = /마무리\s*했습니다|마무리\s*하겠습니다|이상입니다|진료를?\s*마치/.test(text);
  aiBusy = true;
  focusAiInput = true;
  saveState();
  render();
  window.CpxAI.patientReply(aiCtx(c), session.messages, text)
    .then((reply) => {
      aiBusy = false;
      const current = aiSessionFor(c.id);
      current.engine = reply.engine;
      current.messages.push({ role: "patient", text: reply.text, revealId: reply.revealId, worryAsked: reply.worryAsked });
      speakPatientReply(reply.text);
      if (finishing) {
        current.status = "closed";
        current.messages.push({ role: "system", text: "면담이 마무리되었습니다. ‘채점하기’를 눌러 피드백을 받으세요." });
        stopTimer();
      }
      saveState();
      if (state.activeCaseId === c.id) render();
    })
    .catch(() => {
      aiBusy = false;
      render();
    });
}

function gradeAiSession() {
  const c = activeCase();
  const session = aiSessionFor(c.id);
  if (aiBusy || session.status === "idle") return;
  if (!session.messages.some((message) => message.role === "student")) {
    window.alert("아직 대화 기록이 없습니다. 먼저 환자에게 말을 걸어보세요.");
    return;
  }
  session.status = "closed";
  stopTimer();
  aiBusy = true;
  saveState();
  render();
  window.CpxAI.grade(aiCtx(c), session.messages)
    .then((result) => {
      aiBusy = false;
      const current = aiSessionFor(c.id);
      current.result = result;
      current.engine = result.engine;
      current.status = "graded";
      saveState();
      if (state.activeCaseId === c.id) render();
    })
    .catch(() => {
      aiBusy = false;
      render();
    });
}

function retryAiSession() {
  const c = activeCase();
  const session = aiSessionFor(c.id);
  if (aiBusy) return;
  if (session.messages.some((message) => message.role === "student") &&
      !window.confirm("현재 대화 기록을 지우고 처음부터 다시 시작할까요?")) {
    return;
  }
  startAiSession();
}

