document.getElementById("app").addEventListener("keydown", (event) => {
  if (event.key === "Escape" && (state.showExamScope || state.showPastArchive)) {
    state.showExamScope = false;
    state.showPastArchive = false;
    saveState();
    render();
    return;
  }
  if (event.target.id === "aiInput" && event.key === "Enter") {
    event.preventDefault();
    sendAiMessage(event.target.value);
    return;
  }
  if (event.target.id !== "coachInput" || event.key !== "Enter") return;
  event.preventDefault();
  sendCoachMessage(event.target.value);
});

